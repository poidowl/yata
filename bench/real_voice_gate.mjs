#!/usr/bin/env node
/**
 * bench/real_voice_gate.mjs — Rule 1: a diagnostic filter must not fire on benign PD/CC0 real audio.
 *
 *   node bench/real_voice_gate.mjs --cache-dir /tmp/yata_real_wavs --cache-dir /tmp/yata_heldout [--tokiko-dir ../tokiko] [--write]
 *
 * Gate set  = manifest.json benign/historical clips that are PD/CC0 (BY, BY-SA, VOICEVOX excluded; deduped by source+trim)
 *             + tuning_pd_cc0_manifest.json benign clips. The held-out manifest is NOT read unless --confirm-heldout,
 *             and its numbers never feed --write.
 * Tags      : quarantined    = fires on > QUARANTINE_RATE of the gate set (hidden from default/compact text, still in JSON)
 *             tokikoDerived  = fires on <= 10% of the gate set and >= 2/3 of tokiko clips (tag + note only)
 * --write   : regenerates src/falsifiers/gate.mjs (the only place the tags live).
 * Zero npm deps.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { analyzeSamples, DEFAULT_FALSIFIERS, ORIGINAL_6_FALSIFIERS } from "../unkawaii_detector.mjs";
import { readManifest, loadClips, argDirs, isPdCc0, HERE } from "./real_audio_audit/clipset.mjs";

export const QUARANTINE_RATE = 0.2;
const TOKIKO_RATE = 2 / 3;
export const TOKIKO_MAX_REAL_RATE = 0.1;
const argv = process.argv.slice(2);
const dirs = argDirs(argv), fetch = argv.includes("--fetch");
const core = new Set(ORIGINAL_6_FALSIFIERS.map((f) => f.id));
const ids = DEFAULT_FALSIFIERS.map((f) => f.id).filter((id) => !core.has(id));

const seen = new Set();
const gateClips = [
  ...readManifest("manifest.json").clips.filter((c) => /benign|historical/.test(c.auditGroup)),
  ...readManifest("tuning_pd_cc0_manifest.json").clips.filter((c) => /benign/.test(c.group)),
].filter((c) => isPdCc0(c.license, c.sourceUrl) && !seen.has(`${c.sourceUrl}@${c.trimStartSec}`) && seen.add(`${c.sourceUrl}@${c.trimStartSec}`));

const fires = (items) => {
  const n = Object.fromEntries(ids.map((id) => [id, 0]));
  for (const { samples, sampleRate } of items)
    for (const f of analyzeSamples(samples, sampleRate).falsifiers) if (f.triggered && id_ok(f.id)) n[f.id]++;
  return n;
};
const id_ok = (id) => !core.has(id);

const gate = loadClips(gateClips, { dirs, fetch });
const g = fires(gate);
let tok = null, nTok = 0;
const ti = argv.indexOf("--tokiko-dir");
if (ti >= 0) {
  const kuda = await import(pathToFileURL(path.resolve(argv[ti + 1], "kuda.mjs")).href);
  const texts = ["なる", "わたし、にほんご、ちょっとしゃべれます", "おはよう、きょうは、いいてんきだね"];
  const items = texts.flatMap((t) => ["kawaii", "amae", "genki"].map((preset) => {
    const o = kuda.synthKuda(t, { preset, srOut: 24000 });
    return { samples: o.samples || o, sampleRate: 24000 };
  }));
  nTok = items.length; tok = fires(items);
}
let ho = null, nHo = 0;
if (argv.includes("--confirm-heldout")) {
  const h = loadClips(readManifest("heldout_pd_cc0_manifest.json").clips.filter((c) => /benign/.test(c.group)), { dirs, fetch });
  nHo = h.length; ho = fires(h);
}

const N = gate.length, quarantined = {}, tokikoDerived = {};
console.log(`gate set (${N}): ${gate.map((x) => x.clip.id + (x.shaOk === false ? "(SHA MISMATCH)" : "")).join(", ")}`);
console.log(`| filter | gate | ${tok ? `tokiko/${nTok} | ` : ""}${ho ? `heldout(confirm only)/${nHo} | ` : ""}tag |`);
for (const id of ids) {
  const rate = N ? g[id] / N : 0;
  let tag = "";
  if (rate > QUARANTINE_RATE) { tag = "quarantined"; quarantined[id] = { gateFires: g[id], gateN: N }; }
  else if (tok && rate <= TOKIKO_MAX_REAL_RATE && tok[id] / nTok >= TOKIKO_RATE) { tag = "tokiko-derived"; tokikoDerived[id] = { tokikoFires: tok[id], tokikoN: nTok, gateFires: g[id], gateN: N }; }
  if (g[id] || tag || (tok && tok[id]) || (ho && ho[id]))
    console.log(`| ${id} | ${g[id]}/${N} | ${tok ? `${tok[id]} | ` : ""}${ho ? `${ho[id]} | ` : ""}${tag} |`);
}

if (argv.includes("--write")) {
  if (N < 5) throw new Error(`gate set too small (${N}); fetch the clips first`);
  const out = path.resolve(HERE, "../../src/falsifiers/gate.mjs");
  const body = `/**
 * src/falsifiers/gate.mjs — GENERATED by bench/real_voice_gate.mjs --write (do not hand-edit numbers).
 * quarantined   : diagnostic filters firing on > ${QUARANTINE_RATE * 100}% of benign PD/CC0 real audio (gate set, n=${N}).
 *                 Still computed and present in JSON; hidden from default/compact text.
 * tokikoDerived : fire on <= ${TOKIKO_MAX_REAL_RATE * 100}% of the gate set and >= 2/3 of tokiko clips. Tag only: they measure
 *                 "differs from the tokiko build", not "differs from real voices". Do not optimise tokiko against them.
 * Never veto. Core-6 (F1-F6) are never gated here.
 */
export const GATE_SET = ${JSON.stringify({ n: N, ids: gate.map((x) => x.clip.id), generatedAt: new Date().toLocaleDateString("sv") })};
export const QUARANTINED = Object.freeze({
${Object.entries(quarantined).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}
});
export const TOKIKO_DERIVED = Object.freeze({
${Object.entries(tokikoDerived).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}
});
`;
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
